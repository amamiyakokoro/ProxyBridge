#ifndef PB_VERSION_H
#define PB_VERSION_H

// KokoroBox fork version, independent of upstream ProxyBridge releases.
#define PB_VERSION_MAJOR 4
#define PB_VERSION_MINOR 26
#define PB_VERSION_PATCH 10
#define PB_VERSION_BUILD 0

#define PB_STRINGIFY_INNER(value) #value
#define PB_STRINGIFY(value) PB_STRINGIFY_INNER(value)
#define PB_VERSION_STRING PB_STRINGIFY(PB_VERSION_MAJOR) "." PB_STRINGIFY(PB_VERSION_MINOR) "." PB_STRINGIFY(PB_VERSION_PATCH)
#define PB_VERSION_NUMBERS PB_VERSION_MAJOR,PB_VERSION_MINOR,PB_VERSION_PATCH,PB_VERSION_BUILD

#endif
